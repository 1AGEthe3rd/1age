const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const source=fs.readFileSync(require('node:path').join(__dirname,'../living-ticker.js'),'utf8');
const handlers={},captures=new Set(),shown=[];
let opened=0;
const trigger={addEventListener(name,fn){handlers[name]=fn;},setPointerCapture(id){captures.add(id);},hasPointerCapture(id){return captures.has(id);},releasePointerCapture(id){captures.delete(id);}};
const code=source.slice(source.indexOf('    function stepMessage'),source.indexOf("    ticker.addEventListener('pointerenter'"));
const ctx={trigger,announcements:[1,2,3],index:0,drag:null,suppressTap:false,timer:0,animation:{pause(){}},clearTimeout(){},showAnnouncement(){shown.push(ctx.index);},openInfo(){opened++;}};
vm.createContext(ctx);vm.runInContext(code,ctx);
const event=(x,y=0)=>({button:0,pointerId:1,clientX:x,clientY:y,preventDefault(){}});
handlers.pointerdown(event(200));handlers.pointermove(event(145));handlers.pointerup(event(145));handlers.click(event(145));
assert.equal(ctx.index,1,'Dragging left advances');assert.equal(opened,0,'A drag does not open information');
handlers.pointerdown(event(100));handlers.pointermove(event(200));handlers.pointerup(event(200));handlers.click(event(200));
assert.equal(ctx.index,2,'Dragging right replays earlier messages with wraparound');
handlers.pointerdown(event(100));handlers.pointermove(event(102,50));handlers.pointerup(event(102,50));handlers.click(event(102,50));
assert.equal(ctx.index,2,'Vertical scrolling does not change the ticker');assert.equal(opened,0);
handlers.pointerdown(event(100));handlers.pointerup(event(100));handlers.click(event(100));assert.equal(opened,1,'A tap opens information');
handlers.keydown({key:'ArrowRight',preventDefault(){}});assert.equal(ctx.index,0,'Keyboard next wraps');
handlers.pointerdown(event(100));handlers.pointermove(event(40));handlers.pointercancel(event(40));handlers.click(event(40));
assert.equal(opened,1,'Cancelled touch cannot open information');assert.equal(captures.size,0);
console.log('Ticker scrub checks passed: advance, replay, vertical scroll, tap, keyboard and cancellation.');
