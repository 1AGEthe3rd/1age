import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {safeDestination,entityDestinations} from '../search-orbit-model.mjs';
const data=JSON.parse(readFileSync(new URL('../data/search-index.json',import.meta.url)));
const solana=data.find(x=>x.id==='solana');
const nodes=entityDestinations(solana,data);
assert(nodes.some(x=>x.id==='solana-discord'));
assert(nodes.some(x=>x.id==='solana-funding'));
assert.equal(new Set(nodes.map(x=>x.id)).size,nodes.length);
assert(nodes.some(x=>x.id==='anatoly-yakovenko'));
const team=entityDestinations(data.find(x=>x.id==='helius'),data);
assert.equal(team.filter(x=>x.type==='person').length,3,'A shared team URL cannot collapse distinct people in 3D');
assert.equal(new Set(team.filter(x=>x.type==='person').map(x=>x.url)).size,1,'These people share a checked public team page');
for(const value of ['javascript:alert(1)','data:text/html,hello','http://example.com','https://user:password@example.com','/relative'])assert.equal(safeDestination(value),null);
const sample={id:'center',official_links:{website:'https://example.com',x:'javascript:alert(1)'},relationships:[]};
const malicious=[{id:'bad',name:'Bad',official_links:{website:'https://bad.example'},relationships:[{target:'center',status:'inferred',source:'https://example.com'}]}];
assert.equal(entityDestinations(sample,malicious).length,1,'Inferred relationships do not become official destinations');
assert.equal(entityDestinations({id:'empty'},[]).length,0);
assert.equal(entityDestinations(sample,Array.from({length:40},(_,i)=>({id:'r'+i,name:'Resource '+i,type:'community',official_links:{website:'https://example.com/'+i},relationships:[{target:'center',status:'source_checked',source:'https://example.com/source'}]}))).length,16,'Bound scene complexity');
console.log('3D destination model checks passed: real catalog links, provenance, unsafe URL exclusion, deduplication, empty state and scene budget.');
